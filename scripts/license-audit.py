#!/usr/bin/env python3
"""List the licenses of all third-party code shipped in public/vendor/.

Walks the production dependency tree of every vendored top-level package (bundles
inline their dependencies, so the vendor folder alone does not show everything),
reads each package's license from its package.json on unpkg, and writes
THIRD_PARTY_LICENSES.md with the full license texts.

Usage: python3 scripts/license-audit.py
"""

import json
import os
import re
import sys
import time
import urllib.error
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UNPKG = 'https://unpkg.com'

# keep in sync with public/vendor/ and scripts/vendor-plugins.py
ROOTS = [
    'bpmn-js@18.31.0',
    'bpmn-js-color-picker@0.7.2',
    'bpmn-js-properties-panel@5.65.3',
    '@bpmn-io/properties-panel@3.58.1',
    'bpmn-js-differ@3.2.0',
    'bpmn-js-bpmnlint@0.25.0',
    'bpmnlint@12.0.0',
    'bpmn-js-token-simulation@1.1.0',
    'diagram-js-minimap@5.6.0',
    'bpmn-auto-layout@1.3.0',
    'unenv@latest',  # Node.js polyfills esm.sh adds (public/vendor/esm/node/)
]

LICENSE_FILE_RE = re.compile(r'^/(licen[sc]e|copying)(\.(md|txt|markdown))?$', re.I)


def get(url, attempts=6):
    # unpkg occasionally answers 408/429/5xx under load; retry those with backoff
    for i in range(attempts):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'license-audit'})
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read().decode('utf-8', 'replace')
        except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError) as e:
            status = getattr(e, 'code', None)
            if i == attempts - 1 or (status is not None and status not in (408, 429) and status < 500):
                raise
            time.sleep(2 ** i)


def package_json(spec):
    return json.loads(get(f'{UNPKG}/{spec}/package.json'))


def license_of(meta):
    lic = meta.get('license') or meta.get('licenses')
    if isinstance(lic, list):
        lic = ' OR '.join(l.get('type', '?') if isinstance(l, dict) else str(l) for l in lic)
    if isinstance(lic, dict):
        lic = lic.get('type')
    return lic or 'UNKNOWN'


def license_text(name, version):
    try:
        files = json.loads(get(f'{UNPKG}/{name}@{version}/?meta')).get('files', [])
    except (urllib.error.URLError, ValueError):
        return None
    for f in files:
        if LICENSE_FILE_RE.match(f.get('path', '')):
            return get(f'{UNPKG}/{name}@{version}{f["path"]}').strip()
    return None


def main():
    found = {}  # name -> {version, license, text, via}
    queue = [(spec, 'vendored') for spec in ROOTS]
    seen = set()
    while queue:
        spec, via = queue.pop(0)
        if spec in seen:
            continue
        seen.add(spec)
        meta = package_json(spec)
        name, version = meta['name'], meta['version']
        if name not in found:
            found[name] = {'versions': set(), 'license': license_of(meta), 'via': via,
                           'repo': (meta.get('repository') or {}).get('url', '') if isinstance(meta.get('repository'), dict) else meta.get('repository', '')}
        found[name]['versions'].add(version)
        for dep, rng in (meta.get('dependencies') or {}).items():
            queue.append((f'{dep}@{rng}', name))
        print(f'  {name}@{version}: {found[name]["license"]}', file=sys.stderr)

    by_license = {}
    for name, info in found.items():
        by_license.setdefault(info['license'], []).append(name)

    lines = ['# Third-party licenses', '',
             'Generated by `scripts/license-audit.py` from the dependency trees of the packages vendored in '
             '`public/vendor/`. It includes some tooling-only dependencies that are not shipped to the browser.', '',
             '| License | Packages |', '|---|---|']
    for lic, names in sorted(by_license.items(), key=lambda kv: -len(kv[1])):
        lines.append(f'| {lic} | {len(names)}: {", ".join(sorted(names))} |')
    lines.append('')
    for name in sorted(found):
        info = found[name]
        version = sorted(info['versions'])[-1]
        text = license_text(name, version) or f'(No license file in the package; package.json declares "{info["license"]}".)'
        lines += [f'## {name} {", ".join(sorted(info["versions"]))}', '',
                  f'License: {info["license"]}', '', '```', text, '```', '']
    with open(os.path.join(ROOT, 'THIRD_PARTY_LICENSES.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

    print('\nLicense summary:')
    for lic, names in sorted(by_license.items(), key=lambda kv: -len(kv[1])):
        print(f'  {lic:20s} {len(names):3d}  {", ".join(sorted(names))}')


if __name__ == '__main__':
    sys.exit(main())
