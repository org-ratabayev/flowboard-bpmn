// Writes THIRD_PARTY_LICENSES.md: the licenses of all installed runtime dependencies of the
// browser app (bundled into the pages) and the server. Run after `pnpm install`: pnpm license-list
//
// Walks `dependencies`, `optionalDependencies` and `peerDependencies` (not dev dependencies)
// starting from each workspace package, resolving packages the way Node does.

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const START = ['packages/web', 'packages/server'];
const LICENSE_FILE = /^(licen[cs]e|copying)(\.[a-z]+)?$/i;

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));

/** Directory of package `name` as seen from `fromDir`, or null when it is not installed. */
function findPackage(fromDir, name) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return fs.realpathSync(candidate);
    if (dir === path.dirname(dir)) return null;
  }
}

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type || l).join(' OR ');
  return 'UNKNOWN';
}

function licenseText(dir) {
  const file = fs.readdirSync(dir).find((f) => LICENSE_FILE.test(f));
  return file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : null;
}

const found = new Map(); // name -> { license, versions: Set, dir }
const visited = new Set();
const queue = START.map((p) => path.join(ROOT, p));
while (queue.length) {
  const dir = queue.shift();
  if (visited.has(dir)) continue;
  visited.add(dir);
  const pkg = readJson(path.join(dir, 'package.json'));
  const isWorkspace = !dir.includes(`${path.sep}node_modules${path.sep}`);
  if (!isWorkspace) {
    const entry = found.get(pkg.name) ?? { license: licenseOf(pkg), versions: new Set(), dir };
    entry.versions.add(pkg.version);
    found.set(pkg.name, entry);
  }
  const deps = { ...pkg.peerDependencies, ...pkg.optionalDependencies, ...pkg.dependencies };
  for (const name of Object.keys(deps)) {
    const depDir = findPackage(dir, name);
    if (depDir) queue.push(depDir);
  }
}

const byLicense = new Map();
for (const [name, info] of found) byLicense.set(info.license, [...(byLicense.get(info.license) ?? []), name]);

const lines = [
  '# Third-party licenses',
  '',
  'Generated by `pnpm license-list` (`scripts/license-list.mjs`) from the installed runtime dependencies of the browser app ' +
    '(`packages/web`, bundled into the pages) and the server (`packages/server`).',
  '',
  '| License | Packages |',
  '|---|---|'
];
for (const [license, names] of [...byLicense].sort((a, b) => b[1].length - a[1].length)) {
  lines.push(`| ${license} | ${names.length}: ${names.sort().join(', ')} |`);
}
lines.push('');
for (const name of [...found.keys()].sort()) {
  const info = found.get(name);
  const text = licenseText(info.dir) ?? `(No license file in the package; package.json declares "${info.license}".)`;
  lines.push(`## ${name} ${[...info.versions].sort().join(', ')}`, '', `License: ${info.license}`, '', '```', text, '```', '');
}
fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_LICENSES.md'), lines.join('\n'));

console.log(`${found.size} packages:`);
for (const [license, names] of [...byLicense].sort((a, b) => b[1].length - a[1].length)) console.log(`  ${license}: ${names.length}`);
